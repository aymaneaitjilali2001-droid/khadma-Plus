CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('candidate', 'manager')),
  full_name VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS candidate_profiles (
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  phone VARCHAR(30),
  skills TEXT,
  resume_path VARCHAR(500),
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS jobs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(150) NOT NULL,
  company VARCHAR(150) NOT NULL,
  location VARCHAR(100) NOT NULL,
  contract VARCHAR(20) NOT NULL CHECK (contract IN ('CDI', 'CDD', 'Stage', 'Freelance')),
  description TEXT,
  manager_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS job_tags (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id INTEGER NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  tag VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS applications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id INTEGER NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  candidate_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  nom VARCHAR(255) NOT NULL,
  prenom VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL,
  telephone VARCHAR(30) NOT NULL,
  whatsapp BOOLEAN NOT NULL DEFAULT FALSE,
  linkedin VARCHAR(500),
  portfolio VARCHAR(500),
  message TEXT,
  resume_path VARCHAR(500),
  statut VARCHAR(30) NOT NULL DEFAULT 'Pas encore traité'
    CHECK (statut IN ('Pas encore traité', 'Accepté', 'Refusé')),
  applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ai_score INTEGER,
  ai_decision BOOLEAN,
  ai_reasons JSONB,
  ai_summary TEXT,
  ai_evaluated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ai_analyses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id INTEGER NOT NULL UNIQUE REFERENCES applications(id) ON DELETE CASCADE,
  compatibility_score INTEGER NOT NULL,
  matched_skills TEXT,
  missing_skills TEXT,
  recommendation TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_jobs_status ON jobs(status);
CREATE INDEX IF NOT EXISTS idx_applications_job_id ON applications(job_id);
CREATE INDEX IF NOT EXISTS idx_job_tags_job_id ON job_tags(job_id);
